-- NWCMC chatbot schema for Supabase (Postgres).
-- Run in: Supabase Dashboard -> SQL Editor -> New query -> paste -> Run.
-- Table/column names are identical to the Django app so existing data can be imported as-is.

create table if not exists public.chatbot_chatlog (
  id            bigint generated by default as identity primary key,
  "user"        varchar(255),
  request_text  text not null,
  response_text text,
  created_at    timestamptz not null default now()
);
create index if not exists chatbot_chatlog_created_at_idx on public.chatbot_chatlog (created_at desc);

create table if not exists public."chatbot_IVC" (
  id         bigint generated by default as identity primary key,
  content    text,
  source     varchar(255),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists chatbot_ivc_source_idx on public."chatbot_IVC" (source);

create table if not exists public.chatbot_faq (
  id         bigint generated by default as identity primary key,
  question   text not null,
  answer     text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists chatbot_faq_created_at_idx on public.chatbot_faq (created_at desc);

create table if not exists public.chatbot_url (
  id             bigint generated by default as identity primary key,
  url            text not null unique,
  content_hash   varchar(64),
  last_synced_at timestamptz,
  created_at     timestamptz not null default now()
);

create table if not exists public.chatbot_urlchunk_tbl (
  id            bigint generated by default as identity primary key,
  url_source_id bigint not null references public.chatbot_url(id) on delete cascade,
  content       text not null,
  created_at    timestamptz not null default now()
);
create index if not exists chatbot_urlchunk_url_idx on public.chatbot_urlchunk_tbl (url_source_id);

-- Serverless-safe rate limiting (replaces Django's in-memory cache)
create table if not exists public.chatbot_ratelimit (
  key          text primary key,
  count        integer not null,
  window_start timestamptz not null default now()
);

-- Lock the tables down: the app connects with the database role (bypasses RLS),
-- while Supabase's public REST API (anon/authenticated keys) gets NO access.
alter table public.chatbot_chatlog        enable row level security;
alter table public."chatbot_IVC"          enable row level security;
alter table public.chatbot_faq            enable row level security;
alter table public.chatbot_url            enable row level security;
alter table public.chatbot_urlchunk_tbl   enable row level security;
alter table public.chatbot_ratelimit      enable row level security;

